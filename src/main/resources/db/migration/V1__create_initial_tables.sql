CREATE TABLE USER (
    ID UUID PRIMARY KEY,
    EMAIL VARCHAR(256) UNIQUE,
    USERNAME VARCHAR(200),
    PASSWORD VARCHAR(100) CHECK(LENGTH(PASSWORD)>=8),
    SALDO DOUBLE DEFAULT 0.0
    DIA_SALARIO INTEGER,
    VLR_SALARIO DOUBLE,
);



CREATE TYPE TIPO_PAGAMENTO AS ENUM ('DEBITO','CREDITO','DINHEIRO','PIX','OUTROS'); 


CREATE TYPE CATEGORIA AS ENUM ('ALIMENTACAO','LAZER','MORADIA','MOBILIDADE','CONTAS','SAUDE','OUTROS') 

CREATE TABLE RECIBO(
    ID UUID PRIMARY KEY,
    DT_PAGAMENTO DATETIME,
    VALOR DOUBLE,
    DESCRICAO TEXT


)

CREATE TABLE OBJETIVO(
    ID UUID PRIMARY KEY,
    ID_USUARIO UUID REFERENCES USER,
    OBJETIVO VARCHAR(50),
    DESCRICAO TEXT,
    VALOR_ARRECADADO DOUBLE
)




